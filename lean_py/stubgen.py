"""Generate ``.pyi`` type stubs for a Lean library's Python surface.

A :class:`~lean_py.library.LeanLibrary` exposes its ``@[python]`` functions and
``derive_python`` types as dynamic attributes, so editors and type-checkers see
only ``Any``. This module turns the runtime registry (the same
``TypeRepr``/``FuncInfo``/``TypeInfo`` data that drives marshalling) into a
static stub, so the marshaller and the type hints share one source of truth.

Usage::

    from lean_py import LeanLibrary
    lib = LeanLibrary.from_lake("path/to/project", "MyLib", build=True)
    lib.write_stub("MyLib.pyi")            # or
    print(generate_stub(lib.registry, "MyLib"))

or from the command line::

    python -m lean_py.stubgen path/to/project MyLib -o MyLib.pyi

The generated stub declares a ``<Name>Library`` subclass of ``LeanLibrary`` with
typed methods and typed constructor attributes, plus one class per derived
type. Annotate the ``from_lake`` result with it to get completion and checks::

    lib: MyLibLibrary = LeanLibrary.from_lake(...)  # type: ignore[assignment]
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from lean_py.registry import (
    FuncInfo,
    LibraryRegistry,
    TypeInfo,
    TypeRepr,
    py_ident,
)

if TYPE_CHECKING:
    from lean_py.library import LeanLibrary


_HEADER = (
    "# Auto-generated by `python -m lean_py.stubgen`. Do not edit by hand.\n"
    "# Regenerate after changing the Lean library's `@[python]` surface.\n"
)


# `_safe_ident` sanitises an already-short name; `py_ident` does the same but
# also strips a dotted prefix. Type/constructor/function names use `py_ident`.
def _safe_ident(name: str) -> str:
    return py_ident(name)


def _annotation(t: TypeRepr, known_types: set[str], named_prefix: str = "") -> str:
    """Render a ``TypeRepr`` as a Python annotation string.

    Delegates to :meth:`TypeRepr.python_annotation` — the canonical mapping that
    also backs runtime argument validation — so the static hints and the
    runtime predicate can never drift.

    ``known_types`` is the set of short class names the stub defines; a ``named``
    reference resolves to ``named_prefix + short`` when known, else ``Any``. The
    prefix lets the library class reference module-scope type classes through
    aliases without its constructor attributes shadowing them.
    """
    return t.python_annotation(known_types, named_prefix)


def _params(
    fields: tuple[TypeRepr, ...], known_types: set[str], named_prefix: str = ""
) -> str:
    """Positional-only parameter list. The registry carries types but not
    names, so parameters are named ``a0, a1, ...`` and marked positional-only
    (``/``), matching the runtime wrappers, which reject keyword arguments."""
    if not fields:
        return ""
    parts = [
        f"a{i}: {_annotation(f, known_types, named_prefix)}"
        for i, f in enumerate(fields)
    ]
    return ", ".join(parts) + ", /"


# Prefix for the module-level aliases the library class uses to reference type
# classes without its constructor attributes shadowing them.
_ALIAS = "_ty_"


def _emit_type(ti: TypeInfo, known_types: set[str]) -> list[str]:
    """Emit a module-scope class for a derived type.

    Type classes live at module scope so their fields can reference sibling and
    recursive types by their natural names (Python class bodies are not
    enclosing scopes, so nested classes could not see each other).

    Single-constructor structures are callable directly (``Point(x, y)``), so
    the class gets an ``__init__``. Multi-constructor inductives expose each
    constructor as a nested callable class (``Shape.circle(r)``), matching the
    ``_InductiveType`` namespace built at load time.
    """
    lines: list[str] = []
    cls_name = _safe_ident(ti.name)
    doc = f'"""Lean type ``{ti.name}``. Values are ``LeanInductiveValue``s."""'

    if len(ti.ctors) == 1 and not ti.isEnum:
        ctor = ti.ctors[0]
        params = _params(ctor.fields, known_types)
        lines.append(f"class {cls_name}(LeanInductiveValue):")
        lines.append(f"    {doc}")
        lines.append(f"    def __init__(self{', ' + params if params else ''}) -> None: ...")
        return lines

    lines.append(f"class {cls_name}:")
    lines.append(f"    {doc}")
    for ctor in ti.ctors:
        ctor_name = _safe_ident(ctor.name)
        if ctor.fields:
            params = _params(ctor.fields, known_types)
            lines.append(f"    class {ctor_name}(LeanInductiveValue):")
            lines.append(f"        def __init__(self, {params}) -> None: ...")
        else:
            # Nullary constructor: usable as a value (`Color.red`) and in
            # `isinstance`/pattern matching.
            lines.append(f"    class {ctor_name}(LeanInductiveValue): ...")
    return lines


def generate_stub(registry: LibraryRegistry, library_name: str) -> str:
    """Return the text of a ``.pyi`` stub for ``registry``."""
    type_names = [_safe_ident(ti.name) for ti in registry.types]
    known_types = set(type_names)

    out: list[str] = [_HEADER]
    out.append("from typing import Any")
    out.append("")
    out.append("from lean_py.library import LeanLibrary")
    out.append("from lean_py.marshal import LeanInductiveValue")
    out.append("")
    out.append("")

    # Module-scope type classes (natural names, resolvable everywhere).
    for ti in registry.types:
        out.extend(_emit_type(ti, known_types))
        out.append("")
        out.append("")

    # Aliases so the library class can name types without its constructor
    # attributes (`Point: type[_ty_Point]`) shadowing the classes.
    if type_names:
        for tname in type_names:
            out.append(f"{_ALIAS}{tname} = {tname}")
        out.append("")
        out.append("")

    cls_name = _safe_ident(library_name) + "Library"
    out.append(f"class {cls_name}(LeanLibrary):")
    out.append(f'    """Typed view of the ``{library_name}`` Lean library.')
    out.append("")
    out.append("    Annotate the ``from_lake`` result with this class to get")
    out.append("    completion and type-checking for the library's surface::")
    out.append("")
    out.append(f"        lib: {cls_name} = LeanLibrary.from_lake(...)  # type: ignore[assignment]")
    out.append('    """')
    out.append("")

    body: list[str] = []

    # Constructor attributes: `lib.Point`, `lib.Shape`, ... typed via aliases.
    for tname in type_names:
        body.append(f"    {tname}: type[{_ALIAS}{tname}]")

    # Functions. Deduplicate by the short name we actually attribute onto the
    # instance (`declName`'s last segment), preferring the first occurrence.
    seen: set[str] = set()
    for fi in registry.funcs:
        name = _safe_ident(fi.declName)
        if name in seen:
            continue
        seen.add(name)
        params = _params(fi.params, known_types, named_prefix=_ALIAS)
        ret = _annotation(fi.returnType, known_types, named_prefix=_ALIAS)
        sig = f"self{', ' + params if params else ''}"
        body.append(f"    def {name}({sig}) -> {ret}: ...")

    if not any(line.strip() for line in body):
        body.append("    pass")
    out.extend(body)
    out.append("")

    return "\n".join(out)


def generate_stub_for_library(lib: LeanLibrary) -> str:
    """Convenience wrapper: build a stub from a loaded library."""
    return generate_stub(lib.registry, lib.name)


def _main(argv: list[str] | None = None) -> int:
    import argparse

    from lean_py.library import LeanLibrary

    parser = argparse.ArgumentParser(
        prog="python -m lean_py.stubgen",
        description="Generate a .pyi stub for a Lean library's Python surface.",
    )
    parser.add_argument("lake_dir", help="Path to the Lake project directory.")
    parser.add_argument("library_name", help="Lean library name (e.g. MyLib).")
    parser.add_argument(
        "-o", "--output", default=None,
        help="Output path (default: <library_name>.pyi in the current dir).",
    )
    parser.add_argument(
        "--no-build", action="store_true",
        help="Do not run `lake build` before loading the library.",
    )
    args = parser.parse_args(argv)

    lib = LeanLibrary.from_lake(
        args.lake_dir, args.library_name, build=not args.no_build
    )
    stub = generate_stub_for_library(lib)
    out_path = args.output or f"{args.library_name}.pyi"
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(stub)
    print(f"Wrote {out_path} ({len(lib.registry.funcs)} functions, "
          f"{len(lib.registry.types)} types).")
    return 0


if __name__ == "__main__":
    raise SystemExit(_main())
